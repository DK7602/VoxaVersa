#pragma once

#include <juce_audio_formats/juce_audio_formats.h>
#include <unordered_map>

namespace voxa
{

/** Where an exported vocal came from. */
enum class VocalOrigin
{
    Transformed,                 // a real performance reshaped by the DSP voice engine
    AiVoiceModel,                // re-sung by a neural voice model
    SynthesizedSinging,          // Text to Sing guide vocal
    SynthesizedSingingAiVoice,   // Text to Sing re-sung by a neural voice model
    Recording                    // the plug-in's output recorded in the standalone app
};

/** Human- and machine-readable disclosure written into every file VoxaVersa exports
    (RIFF INFO comment/software + BWF description/originator). Part of VoxaVersa's marking of
    synthetic audio under EU AI Act Article 50(2), together with the inaudible watermark (core/Watermark.h). */
inline std::unordered_map<juce::String, juce::String> disclosureMetadata (VocalOrigin origin, const juce::String& voiceName)
{
    juce::String statement;
    switch (origin)
    {
        case VocalOrigin::AiVoiceModel:
            statement = "AI-generated vocal: re-sung by the VoxaVersa AI voice model \"" + voiceName + "\".";
            break;
        case VocalOrigin::SynthesizedSinging:
            statement = "Synthetic singing generated by VoxaVersa Text to Sing (voice \"" + voiceName + "\").";
            break;
        case VocalOrigin::SynthesizedSingingAiVoice:
            statement = "AI-generated vocal: synthetic singing from VoxaVersa Text to Sing, re-sung by the AI voice model \""
                        + voiceName + "\".";
            break;
        case VocalOrigin::Recording:
            statement = "Recorded from VoxaVersa: may contain AI-generated or digitally transformed vocals (voice \""
                        + voiceName + "\").";
            break;
        case VocalOrigin::Transformed:
        default:
            statement = "Vocal digitally transformed with VoxaVersa (voice \"" + voiceName + "\").";
            break;
    }

    std::unordered_map<juce::String, juce::String> metadata;
    metadata[juce::WavAudioFormat::riffInfoSoftware] = juce::String ("VoxaVersa ") + VOXAVERSA_VERSION_STRING;
    metadata[juce::WavAudioFormat::riffInfoComment2] = statement;
    metadata[juce::WavAudioFormat::bwavDescription] = statement.substring (0, 256);
    metadata[juce::WavAudioFormat::bwavOriginator] = "VoxaVersa";
    metadata[juce::WavAudioFormat::bwavOriginationDate] = juce::Time::getCurrentTime().formatted ("%Y-%m-%d");
    metadata[juce::WavAudioFormat::bwavOriginationTime] = juce::Time::getCurrentTime().formatted ("%H:%M:%S");
    return metadata;
}

} // namespace voxa
